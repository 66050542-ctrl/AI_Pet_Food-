def get_food_prices(food_names):

    try:

        base_dir = os.path.dirname(os.path.abspath(__file__))
        csv_path = os.path.join(base_dir, "food_database.csv")

        food_df = pd.read_csv(csv_path)

        results = []

        for food_name in food_names:

            food_name = str(food_name)

            matched = food_df[
                food_df.apply(
                    lambda row:
                    str(row["brand"]).lower() in food_name.lower()
                    and
                    str(row["formula"]).lower() in food_name.lower(),
                    axis=1
                )
            ]

            if not matched.empty:

                row = matched.iloc[0]

                results.append({
                    "brand": str(row["brand"]),
                    "formula": str(row["formula"]),
                    "price": float(row["price_per_kg"])
                })

        return results

    except Exception as e:

        print("Price error:", e)

        return []

