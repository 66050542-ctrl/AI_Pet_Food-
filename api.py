@app.route("/recommend", methods=["POST"])
def recommendation():

    data = request.json

    pet_type = data.get("pet_type", "Dog")
    breed = data.get("breed", "")
    age_years = float(data.get("age_years", 1))
    weight_kg = float(data.get("weight_kg", 1))
    health_issue = data.get("health_issue", "Healthy")
    activity_level = data.get("activity_level", "Medium")
    budget_per_kg = float(data.get("budget_per_kg", 200))

    result = recommend.recommend_food(
        pet_type=pet_type,
        breed=breed,
        age_years=age_years,
        weight_kg=weight_kg,
        health_issue=health_issue,
        activity_level=activity_level,
        budget_per_kg=budget_per_kg
    )

    return jsonify({
        "prediction": result["prediction"],
        "confidence": result["confidence"],
        "recommended_foods": result["recommended_foods"]
    })


