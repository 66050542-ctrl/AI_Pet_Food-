def parse_pet_message(message):

    text = message.strip()

    text_lower = text.lower()

    # ------------------------------
    # ประเภทสัตว์
    # ------------------------------
    if (
        "สุนัข" in text
        or "หมา" in text
        or "dog" in text_lower
    ):
        pet_type = "Dog"

    elif (
        "แมว" in text
        or "cat" in text_lower
    ):
        pet_type = "Cat"

    else:
        pet_type = "Dog"


    # ------------------------------
    # สายพันธุ์
    # ------------------------------
    breed = ""

    breeds = [
        "Golden Retriever",
        "Labrador Retriever",
        "Poodle",
        "Chihuahua",
        "Pomeranian",
        "Shih Tzu",
        "French Bulldog",
        "German Shepherd",
        "Siberian Husky",
        "Beagle",
        "Corgi",
        "Dachshund",
        "Yorkshire Terrier",
        "Rottweiler",
        "Persian",
        "British Shorthair",
        "Scottish Fold",
        "Siamese",
        "American Shorthair",
        "Bengal",
        "Maine Coon",
        "Ragdoll",
        "Sphynx",
        "Exotic Shorthair"
    ]

    for b in breeds:

        if b.lower() in text_lower:

            breed = b
            break


    # ------------------------------
    # อายุ
    # ------------------------------
    age_years = extract_number(
        r"อายุ\s*(\d+(?:\.\d+)?)\s*(?:ปี|ขวบ)?",
        text,
        1
    )


    # ------------------------------
    # น้ำหนัก
    # ------------------------------
    weight_kg = extract_number(
        r"น้ำหนัก\s*(\d+(?:\.\d+)?)\s*(?:กิโลกรัม|กิโล|kg|กก\.)?",
        text,
        1
    )


    # ------------------------------
    # งบประมาณ
    # ------------------------------
    budget_per_kg = extract_number(
        r"(?:งบประมาณ|งบ|ราคา)\s*(\d+(?:\.\d+)?)\s*(?:บาท)?\s*(?:ต่อกิโลกรัม|/กก\.|/kg|ต่อกก\.)?",
        text,
        200
    )


    # ------------------------------
    # ปัญหาสุขภาพ
    # ------------------------------
    if (
        "ข้อต่อ" in text
        or "joint" in text_lower
    ):
        health_issue = "joint issues"

    elif (
        "ผิวหนัง" in text
        or "ผิว" in text
        or "แพ้" in text
        or "sensitive" in text_lower
    ):
        health_issue = "skin sensitivity"

    elif (
        "น้ำหนักเกิน" in text
        or "อ้วน" in text
        or "weight" in text_lower
    ):
        health_issue = "weight problem"

    elif (
        "สูงอายุ" in text
        or "แก่" in text
        or "senior" in text_lower
    ):
        health_issue = "senior"

    else:
        health_issue = "Healthy"


    # ------------------------------
    # ระดับกิจกรรม
    # ------------------------------
    if (
        "high" in text_lower
        or "สูง" in text
    ):
        activity_level = "High"

    elif (
        "low" in text_lower
        or "ต่ำ" in text
    ):
        activity_level = "Low"

    else:
        activity_level = "Medium"


    return {
        "pet_type": pet_type,
        "breed": breed,
        "age_years": age_years,
        "weight_kg": weight_kg,
        "health_issue": health_issue,
        "activity_level": activity_level,
        "budget_per_kg": budget_per_kg
    }


